// Builds desktop/plugin.js: one ES module that imports only the Hermes plugin SDK and React.
// Run with `node build.mjs`. No dependencies.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.dirname(fileURLToPath(import.meta.url));
const read = p => fs.readFileSync(path.join(root, p), 'utf8');
// Order matters: later files use names defined by earlier ones.
// Scenes ship from scenes/<id>/ (art.js + scene.mjs); folders starting with _ (the template) are not bundled.
export const SCENE_IDS = fs.readdirSync(path.join(root, 'scenes')).filter(d => !d.startsWith('_') && !d.startsWith('.')).sort();
export const SOURCES = [...SCENE_IDS.map(id => `scenes/${id}/scene.mjs`), 'src/scenes.mjs', 'src/scene-time.mjs', 'src/controller.mjs', 'src/layout.mjs', 'src/overlay.mjs', 'src/character.mjs', 'src/scene.mjs', 'src/controls.mjs', 'src/plugin.mjs'];
export function bundle() {
  const header = "import * as sdk from '@hermes/plugin-sdk';\nimport { createElement, useEffect, useRef } from 'react';\n" +
    '// Generated by build.mjs from src/ and scenes/. Edit those, not this file.\n';
  // Each scene's art.js runs in its own function scope and hands back module.exports (draw, STATES, ...).
  const art = 'const ART={\n' + SCENE_IDS.map(id => `${JSON.stringify(id)}:(()=>{const module={exports:{}};\n${read(`scenes/${id}/art.js`)}\nreturn module.exports;})(),\n`).join('') + '};\n';
  const body = SOURCES.map(p => read(p).replace(/^import .*;\n/gm, '').replaceAll('export function ', 'function ').replaceAll('export const ', 'const ')).join('\n');
  return header + art + body;
}
if (process.argv[1] === fileURLToPath(import.meta.url)) {
  fs.writeFileSync(path.join(root, 'desktop/plugin.js'), bundle());
  console.log('Built desktop/plugin.js');
}
